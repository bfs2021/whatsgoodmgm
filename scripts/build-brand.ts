// Regenerates every brand asset from the master vector, public/logo.svg
// (martini + coffee, traced from the original artwork). Run after editing it:
//   npx tsx scripts/build-brand.ts
import { readFileSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'

const INK = '#3a2c22'
const CREAM = '#f6efe3'
const DARK_INK = '#ede8dd' // --ink in the dark theme

const master = readFileSync('public/logo.svg', 'utf8')
const [, vbW, vbH] = master.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/)!.map(Number)
const d = master.match(/ d="([^"]+)"/)![1]

// the mark centered in a square canvas, `pad` = share of the side left empty
function squareSvg(pad: number, opts: { bg?: string; radius?: number; fill?: string } = {}) {
  const side = Math.max(vbW, vbH) / (1 - pad)
  const x = (side - vbW) / 2
  const y = (side - vbH) / 2
  const bg = opts.bg
    ? `<rect width="${side}" height="${side}" rx="${(opts.radius ?? 0) * side}" fill="${opts.bg}"/>`
    : ''
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${side} ${side}">${bg}<path transform="translate(${x} ${y})" fill="${opts.fill ?? INK}" fill-rule="evenodd" d="${d}"/></svg>`
}

const png = (svg: string, size: number) =>
  sharp(Buffer.from(svg), { density: 300 }).resize(size, size).png().toBuffer()

// .ico holding PNG entries (supported by every browser that still asks for .ico)
function ico(images: { size: number; data: Buffer }[]) {
  const header = Buffer.alloc(6 + 16 * images.length)
  header.writeUInt16LE(0, 0)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  let offset = header.length
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i
    header.writeUInt8(size >= 256 ? 0 : size, e)
    header.writeUInt8(size >= 256 ? 0 : size, e + 1)
    header.writeUInt16LE(1, e + 4) // planes
    header.writeUInt16LE(32, e + 6) // bpp
    header.writeUInt32LE(data.length, e + 8)
    header.writeUInt32LE(offset, e + 12)
    offset += data.length
  })
  return Buffer.concat([header, ...images.map(i => i.data)])
}

async function main() {
  // tab icon: transparent, ink on light browser chrome, cream on dark
  const side = Math.max(vbW, vbH) / 0.96
  writeFileSync(
    'src/app/icon.svg',
    squareSvg(0.04).replace(
      `viewBox="0 0 ${side} ${side}">`,
      `viewBox="0 0 ${side} ${side}"><style>path{fill:${INK}}@media (prefers-color-scheme:dark){path{fill:${DARK_INK}}}</style>`,
    ).replace(` fill="${INK}"`, ''),
  )

  // .ico fallback + search results: cream tile so it reads on any background
  const tile = squareSvg(0.14, { bg: CREAM, radius: 0.18 })
  writeFileSync(
    'src/app/favicon.ico',
    ico(await Promise.all([16, 32, 48].map(async size => ({ size, data: await png(tile, size) })))),
  )

  // iOS rounds its own corners: full-bleed cream square
  writeFileSync('src/app/apple-icon.png', await png(squareSvg(0.2, { bg: CREAM }), 180))

  // PWA icons; 0.24 padding keeps the mark inside Android's maskable safe zone
  const pwa = squareSvg(0.24, { bg: CREAM })
  writeFileSync('public/icon-192.png', await png(pwa, 192))
  writeFileSync('public/icon-512.png', await png(pwa, 512))

  // path data for the React <Logo /> and the og:image
  writeFileSync(
    'src/components/logoPath.ts',
    `// generated by scripts/build-brand.ts from public/logo.svg - do not edit\n` +
      `export const LOGO_VIEWBOX = '0 0 ${vbW} ${vbH}'\n` +
      `export const LOGO_ASPECT = ${(vbW / vbH).toFixed(4)}\n` +
      `export const LOGO_PATH =\n  '${d}'\n`,
  )
  console.log('brand assets written')
}

main()
